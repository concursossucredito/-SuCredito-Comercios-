-- Segunda etapa: asignar sucursal y cuotas a cada número de comercio.
-- No elimina ni modifica los códigos ni las cuotas actuales de comercios_cuotas.
-- Ejecutar una sola vez en Supabase > SQL Editor.

alter table public.comercios_codigos
  add column if not exists sucursal text;

create table if not exists public.comercios_codigos_cuotas (
  id bigint generated by default as identity primary key,
  codigo_id bigint not null references public.comercios_codigos(id) on delete cascade,
  cantidad integer not null check (cantidad between 1 and 12),
  etiqueta text not null default '',
  activa boolean not null default true,
  orden integer not null default 0,
  creado_en timestamptz not null default now(),
  constraint comercios_codigos_cuotas_unica unique (codigo_id, cantidad)
);

create index if not exists comercios_codigos_cuotas_codigo_idx
  on public.comercios_codigos_cuotas(codigo_id);

alter table public.comercios_codigos_cuotas enable row level security;

drop policy if exists "comercios_codigos_cuotas_public_read"
  on public.comercios_codigos_cuotas;
create policy "comercios_codigos_cuotas_public_read"
  on public.comercios_codigos_cuotas
  for select using (
    activa = true
    and exists (
      select 1 from public.comercios_codigos c
      where c.id = codigo_id and c.activo = true
    )
  );

drop policy if exists "comercios_codigos_cuotas_admin_all"
  on public.comercios_codigos_cuotas;
create policy "comercios_codigos_cuotas_admin_all"
  on public.comercios_codigos_cuotas
  for all using (
    exists (
      select 1 from public.comercios_admins a
      where a.user_id = auth.uid() and a.activo = true
    )
  )
  with check (
    exists (
      select 1 from public.comercios_admins a
      where a.user_id = auth.uid() and a.activo = true
    )
  );

comment on column public.comercios_codigos.sucursal is
  'Sucursal asociada al número de comercio; admite NULL para códigos aún no clasificados.';
comment on table public.comercios_codigos_cuotas is
  'Cuotas específicas por número de comercio. Las cuotas antiguas por comercio/localidad se conservan como compatibilidad.';
