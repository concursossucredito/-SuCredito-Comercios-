-- Identificación de comercios por código. Un comercio puede tener varios códigos.
-- Ejecutar una sola vez en Supabase > SQL Editor.
create table if not exists public.comercios_codigos (
  id bigint generated by default as identity primary key,
  comercio_id uuid not null references public.comercios(id) on delete cascade,
  codigo text not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint comercios_codigos_codigo_unique unique (codigo),
  constraint comercios_codigos_codigo_no_vacio check (length(trim(codigo)) > 0)
);
create index if not exists comercios_codigos_comercio_idx on public.comercios_codigos(comercio_id);
alter table public.comercios_codigos enable row level security;
drop policy if exists "comercios_codigos_public_read" on public.comercios_codigos;
create policy "comercios_codigos_public_read" on public.comercios_codigos for select using (activo = true);
drop policy if exists "comercios_codigos_admin_all" on public.comercios_codigos;
create policy "comercios_codigos_admin_all" on public.comercios_codigos for all using (
  exists(select 1 from public.comercios_admins a where a.user_id = auth.uid() and a.activo = true)
) with check (
  exists(select 1 from public.comercios_admins a where a.user_id = auth.uid() and a.activo = true)
);
